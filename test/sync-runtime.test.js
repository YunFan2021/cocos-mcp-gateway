'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict');
const fs=require('fs'),os=require('os'),path=require('path'),cp=require('child_process');
const {syncRuntime}=require('../scripts/sync-runtime');
test('同步默认只读，拒绝本地改动，失败回滚，成功保留备份',t=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'mcp-sync-test-'));
 t.after(()=>fs.rmSync(dir,{recursive:true,force:true}));
 const source=dir+'/source',root=dir+'/gateway';
 for(const p of [source+'/server',source+'/router',source+'/cli/bin',root+'/runtime/router',root+'/runtime/cli',root+'/extension'])fs.mkdirSync(p,{recursive:true});
 for(const f of ['main.js','server/tools.js','server/editor-bridge.js','router/bin.js','cli/bin/cocos-mcp-cli.js'])fs.writeFileSync(source+'/'+f,'new');
 fs.copyFileSync(require.resolve('../extension/server/identity'),source+'/server/identity.js');
 fs.writeFileSync(source+'/package.json','{"version":"test"}');
 const identity=require(source+'/server/identity');
 fs.writeFileSync(source+'/maintenance-manifest.json',JSON.stringify(identity.buildManifest(source)));
 for(const p of ['runtime/router','runtime/cli','extension'])fs.writeFileSync(root+'/'+p+'/old','old');
 const git=args=>cp.execFileSync('git',args,{cwd:root,stdio:'pipe'});
 git(['init']);git(['add','.']);git(['-c','user.name=Test','-c','user.email=test@example.invalid','commit','-m','fixture']);
 assert.equal(syncRuntime(source,root).status,'dry_run');
 assert.equal(fs.readFileSync(root+'/extension/old','utf8'),'old');
 fs.writeFileSync(root+'/extension/local','keep');
 assert.throws(()=>syncRuntime(source,root,true),/LOCAL_CHANGES/);fs.unlinkSync(root+'/extension/local');
 let count=0;
 assert.throws(()=>syncRuntime(source,root,true,(a,b)=>{if(++count===3)throw Error('INJECTED');fs.renameSync(a,b);}),/INJECTED/);
 assert.equal(fs.readFileSync(root+'/runtime/router/old','utf8'),'old');
 assert.equal(fs.readFileSync(root+'/extension/old','utf8'),'old');
 const result=syncRuntime(source,root,true);
 assert.equal(result.status,'synced');assert.ok(fs.existsSync(result.backup+'/old-2/old'));
 assert.equal(fs.readFileSync(root+'/extension/main.js','utf8'),'new');
});
